import {
  ArrowLeft,
  ArrowRight,
  ArrowSquareOut,
  ArrowsClockwise,
  BookOpenText,
  CaretUpDown,
  ChatCircle,
  Check,
  Copy,
  DownloadSimple,
  GearSix,
  GitCommit,
  GraduationCap,
  House,
  Info,
  Kanban,
  Link,
  List,
  MagnifyingGlass,
  Moon,
  PaperPlaneRight,
  Plus,
  Printer,
  Question,
  Receipt,
  Scales,
  SignOut,
  SquaresFour,
  Sun,
  Table,
  Users,
  Warning,
  X,
} from "@phosphor-icons/react/ssr";
import type { Icon as PhosphorIcon } from "@phosphor-icons/react/lib";

const map = {
  overview: SquaresFour,
  trace: Table,
  stories: BookOpenText,
  board: Kanban,
  commits: GitCommit,
  decisions: Scales,
  chat: ChatCircle,
  ask: Question,
  receipts: Receipt,
  viva: GraduationCap,
  settings: GearSix,
  home: House,
  search: MagnifyingGlass,
  plus: Plus,
  check: Check,
  x: X,
  sync: ArrowsClockwise,
  link: Link,
  arrow: ArrowRight,
  back: ArrowLeft,
  sun: Sun,
  moon: Moon,
  logout: SignOut,
  menu: List,
  external: ArrowSquareOut,
  print: Printer,
  copy: Copy,
  mentor: Users,
  download: DownloadSimple,
  send: PaperPlaneRight,
  warn: Warning,
  info: Info,
  updown: CaretUpDown,
} satisfies Record<string, PhosphorIcon>;

export type IconName = keyof typeof map;

export function Icon({ name, size = 16, className, bold = false }: { name: IconName; size?: number; className?: string; bold?: boolean }) {
  const C = map[name];
  return <C size={size} weight={bold ? "bold" : "regular"} className={className} aria-hidden />;
}
